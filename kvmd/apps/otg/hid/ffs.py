import os
import select
import struct
import errno

from typing import Callable

from ....logging import get_logger

from . import Hid


# =====
# FunctionFS ABI: include/uapi/linux/usb/functionfs.h
_DESCRIPTORS_MAGIC_V2 = 3
_STRINGS_MAGIC = 2
_HAS_FS_DESC = 1
_HAS_HS_DESC = 2

EVENT_SIZE = 12  # struct usb_functionfs_event: 8 bytes of setup packet, 1 byte type, 3 bytes padding
EVENT_SETUP = 4
_EVENT_NAMES = {
    0: "BIND",
    1: "UNBIND",
    2: "ENABLE",
    3: "DISABLE",
    4: "SETUP",
    5: "SUSPEND",
    6: "RESUME",
}

# USB and HID class constants
_LANG_EN_US = 0x0409
_DT_INTERFACE = 4
_DT_ENDPOINT = 5
_DT_HID = 0x21
_DT_HID_REPORT = 0x22
_CLASS_HID = 3
_BCD_HID = 0x0111
_EP_INTERRUPT = 3
_EP_MIN_PACKET = 8

_REQ_GET_DESCRIPTOR = 6
_HID_REQ_GET_REPORT = 1
_HID_REQ_GET_IDLE = 2
_HID_REQ_SET_IDLE = 10
_HID_REPORT_INPUT = 1

# bmRequestType values (direction | type | recipient=interface)
_RT_STANDARD_IN = 0x81
_RT_CLASS_IN = 0xA1
_RT_CLASS_OUT = 0x21


# =====
def make_descriptors(hids: list[Hid]) -> bytes:
    """
    Build the FunctionFS descriptor blob for one HID interface per given Hid.

    Every interface gets exactly one interrupt IN endpoint and no OUT endpoint.
    This is the whole point of the FunctionFS backend: the configfs f_hid function
    always adds an interrupt OUT endpoint on kernels without the no_out_endpoint
    attribute, and some USB KVM switches re-emulate such composite devices
    with colliding OUT endpoint addresses, which the host then rejects.
    """

    assert 0 < len(hids) <= 15  # One interface per HID, endpoint addresses 0x81..0x8F
    fs_descs = _make_descriptors_set(hids, high_speed=False)
    hs_descs = _make_descriptors_set(hids, high_speed=True)
    count = 3 * len(hids)  # interface + HID + endpoint descriptors per interface
    header = struct.pack(
        "<5I",
        _DESCRIPTORS_MAGIC_V2,
        20 + len(fs_descs) + len(hs_descs),
        (_HAS_FS_DESC | _HAS_HS_DESC),
        count,
        count,
    )
    return (header + fs_descs + hs_descs)


def make_strings(names: list[str]) -> bytes:
    """
    Build the FunctionFS strings blob: one en-US iInterface string per interface.
    The interface descriptors reference these strings by index, starting from 1.
    """

    assert len(names) > 0
    data = struct.pack("<H", _LANG_EN_US) + b"".join(name.encode("utf-8") + b"\0" for name in names)
    return (struct.pack("<4I", _STRINGS_MAGIC, 16 + len(data), len(names), 1) + data)


def make_hid_descriptor(hid: Hid) -> bytes:
    return struct.pack("<BBHBBBH", 9, _DT_HID, _BCD_HID, 0, 1, _DT_HID_REPORT, len(hid.report_descriptor))


def _make_descriptors_set(hids: list[Hid], high_speed: bool) -> bytes:
    descs = b""
    for (index, hid) in enumerate(hids):
        # Both subclass and protocol are 0 (no boot protocol), so the host never
        # sends SET_PROTOCOL and always expects the report-protocol formats
        # generated by the kvmd HID plugin. This is why hid.subclass/hid.protocol
        # are intentionally not used here.
        descs += struct.pack("<9B", 9, _DT_INTERFACE, index, 0, 1, _CLASS_HID, 0, 0, index + 1)
        descs += make_hid_descriptor(hid)
        descs += struct.pack(
            "<BBBBHB",
            7, _DT_ENDPOINT,
            (0x80 | (index + 1)),  # IN endpoint
            _EP_INTERRUPT,
            max(_EP_MIN_PACKET, hid.report_length),
            (4 if high_speed else 1),  # bInterval: 1ms for FS, 2^(4-1) microframes = 1ms for HS
        )
    return descs


# =====
def handle_setup(fd: int, setup: bytes, hids: list[Hid], idle: list[int]) -> None:
    """
    Answer one control request that the kernel forwarded to ep0.

    Requests to the interface arrive here because FunctionFS does not know the HID class.
    The host is answered with a data stage (write to ep0 for IN requests, read for OUT)
    or stalled by performing the opposite operation, as described in the FunctionFS docs.
    """

    (request_type, request, value, index, length) = struct.unpack("<BBHHH", setup)
    response: (bytes | None) = None

    if index < len(hids):
        hid = hids[index]
        if request_type == _RT_STANDARD_IN and request == _REQ_GET_DESCRIPTOR:
            if (value >> 8) == _DT_HID_REPORT:
                response = hid.report_descriptor
            elif (value >> 8) == _DT_HID:
                response = make_hid_descriptor(hid)
        elif request_type == _RT_CLASS_IN:
            if request == _HID_REQ_GET_REPORT and (value >> 8) == _HID_REPORT_INPUT:
                response = bytes(hid.report_length)  # Neutral state: no buttons, no movement
            elif request == _HID_REQ_GET_IDLE:
                response = bytes([idle[index]])
        elif request_type == _RT_CLASS_OUT and request == _HID_REQ_SET_IDLE and length == 0:
            idle[index] = (value >> 8)
            os.read(fd, 0)  # Acknowledge the no-data OUT request
            return

    if response is not None:
        os.write(fd, response[:length])
    elif request_type & 0x80:
        os.read(fd, 0)  # Stall an unsupported IN request
    else:
        os.write(fd, b"")  # Stall an unsupported OUT request


def serve(fd: int, hids: list[Hid], stopped: Callable[[], bool]) -> None:
    """
    Process ep0 events until stopped() becomes true. The ep0 descriptor must be opened
    and the descriptors/strings already written, i.e. the function must be active.
    """

    logger = get_logger()
    idle = [0] * len(hids)
    while not stopped():
        if not select.select([fd], [], [], 0.5)[0]:
            continue
        try:
            # Read exactly one event: a SETUP event must be answered before the next read().
            event = os.read(fd, EVENT_SIZE)
        except OSError as ex:
            if _is_transient(ex):
                continue
            raise
        if len(event) != EVENT_SIZE:
            raise RuntimeError(f"Invalid FunctionFS event length: {len(event)}")
        event_type = event[8]
        if event_type == EVENT_SETUP:
            try:
                handle_setup(fd, event[:8], hids, idle)
            except OSError as ex:
                if not _is_transient(ex):
                    raise
        else:
            logger.info("FunctionFS event: %s", _EVENT_NAMES.get(event_type, str(event_type)))


def _is_transient(ex: OSError) -> bool:
    # EL2HLT/ESRCH are how the kernel reports a deliberate stall,
    # EIDRM means the setup was superseded by a new event.
    return (ex.errno in (errno.EIDRM, errno.EL2HLT, errno.ESRCH, errno.ESHUTDOWN, errno.EINTR))
